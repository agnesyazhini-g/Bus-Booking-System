    private void confirmButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_confirmButtonActionPerformed
String name = nameField.getText().trim();
String ageText = ageField.getText().trim();
String gender = genderComboBox.getSelectedItem().toString();



int age;

try {
    age = Integer.parseInt(ageText);
} catch (NumberFormatException e) {
    JOptionPane.showMessageDialog(this,
            "Please enter a valid age.");
    return;
}

if (age <= 0 || age > 120) {
    JOptionPane.showMessageDialog(this,
            "Please enter a valid age between 1 and 120.");
    return;
}





try {
    String details =
            "Name: " + name + System.lineSeparator()
            + "Age: " + age + System.lineSeparator()
            + "Gender: " + gender + System.lineSeparator()
          ;

    java.nio.file.Files.writeString(
            java.nio.file.Path.of("passenger_info.txt"),
            details,
            java.nio.charset.StandardCharsets.UTF_8
    );

    JOptionPane.showMessageDialog(this,
            "Passenger details saved successfully!");

    BookingsFrame bookings = new BookingsFrame();
    bookings.setVisible(true);
    this.dispose();

} catch (java.io.IOException e) {
    JOptionPane.showMessageDialog(this,
            "Could not save passenger details.");
}        // TODO add your handling code here:
    }//GEN-LAST:event_confirmButtonActionPerformed


    private void loginButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_loginButtonActionPerformed
String username = usernameField.getText().trim();
String password = new String(passwordField.getPassword());

if (username.isEmpty() || password.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Please enter username and password.");
    return;
}

try {
    java.nio.file.Files.writeString(
        java.nio.file.Path.of("login_info.txt"),
        "Username: " + username + System.lineSeparator()
        + "Password: " + password + System.lineSeparator(),
        java.nio.charset.StandardCharsets.UTF_8
    );

    JOptionPane.showMessageDialog(this, "Login information saved!");

    SearchFrame search = new SearchFrame();
    search.setVisible(true);
    this.dispose();

} catch (java.io.IOException e) {
    JOptionPane.showMessageDialog(this,
            "Error saving login information: " + e.getMessage());
}       // TODO add your handling code here:
    }//GEN-LAST:event_loginButtonActionPerformed


    private void searchButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_searchButtonActionPerformed
String from = fromField.getText().trim();
String to = toField.getText().trim();
String date = dateField.getText().trim();

if (from.isEmpty() || to.isEmpty() || date.isEmpty()) {
    JOptionPane.showMessageDialog(this,
            "Please enter From, To and Journey Date.");
    return;
}

if (from.equalsIgnoreCase(to)) {
    JOptionPane.showMessageDialog(this,
            "From and To cannot be the same.");
    return;
}

try {
    java.nio.file.Files.writeString(
        java.nio.file.Path.of("search_info.txt"),
        "From: " + from + System.lineSeparator()
        + "To: " + to + System.lineSeparator()
        + "Journey Date: " + date + System.lineSeparator(),
        java.nio.charset.StandardCharsets.UTF_8
    );
} catch (java.io.IOException e) {
    JOptionPane.showMessageDialog(this,
            "Could not save search details.");
    return;
}

// Display one sample bus
busDetailsLabel.setText(
    "<html><b>ABC Travels</b><br>"
    + from + " to " + to + "<br>"
    + "Departure: 09:00 PM<br>"
    + "Arrival: 05:00 AM<br>"
    + "Fare: Rs. 800</html>"
);

selectBusButton.setVisible(true);        // TODO add your handling code here:
    }//GEN-LAST:event_searchButtonActionPerformed


private void updateSeatSummary() {
    selectedSeats.clear();

    JToggleButton[] seats = {
        seat1, seat2, seat3, seat4,
        seat5, seat6, seat7, seat8,
        seat9, seat10, seat11, seat12,
        seat13, seat14, seat15, seat16,
        seat17, seat18, seat19, seat20
    };

    for (int i = 0; i < seats.length; i++) {
        if (seats[i].isSelected()) {
            selectedSeats.add(i + 1);
        }
    }

    selectedSeatsLabel.setText("Selected Seats: " + selectedSeats);
    totalFareLabel.setText(
        "Total Fare: Rs. " + (selectedSeats.size() * FARE_PER_SEAT)
    );
}
